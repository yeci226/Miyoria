// @miyoria/contracts/ext: the protocol between the host and an extension process
// (docs/protocols/extension-rpc.md). JSON-RPC 2.0 over the extension's stdin and stdout, one
// `Content-Length` frame per message; this part holds the shape of every message, the version
// and the bounds. The SDK (`@miyoria/sdk`) is the code that speaks it.
//
// Within a version a change is additive only: a new field is optional or has a default, and a
// receiver ignores a message, an event type or a key it does not know.

